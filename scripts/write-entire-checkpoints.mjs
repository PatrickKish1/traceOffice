import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const log = execFileSync("git", ["log", "-30", "--format=%H%x1f%s%x1f%b%x1e"], { encoding: "utf8" });
const checkpoints = [];
for (const record of log.split("\x1e")) {
  const [sha, subject, body] = record.trim().split("\x1f");
  const match = /Entire-Checkpoint:\s*([0-9A-Z]{26})/.exec(body ?? "");
  if (!sha || !match) continue;
  checkpoints.push({ sha, id: match[1], subject: (subject ?? "").replaceAll("\\", "\\\\").replaceAll("`", "\\`") });
}

const lines = checkpoints.map((item) => `  { sha: "${item.sha}", id: "${item.id}", subject: \`${item.subject}\` },`).join("\n");
const source = `/** Checkpoints already linked to commits on this repo. Regenerated by scripts/write-entire-checkpoints.mjs. */
export const ENTIRE_REPO = { owner: "PatrickKish1", name: "traceOffice" } as const;

export interface EntireCheckpoint {
  sha: string;
  id: string;
  subject: string;
}

export const ENTIRE_CHECKPOINTS: EntireCheckpoint[] = [
${lines}
];
`;

writeFileSync(new URL("../src/entireCheckpoints.ts", import.meta.url), source);
console.log(`wrote ${checkpoints.length} checkpoints`);
